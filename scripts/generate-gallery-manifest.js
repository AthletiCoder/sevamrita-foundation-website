/**
 * Scans public/images/gallery/<Folder>/ for .jpg / .jpeg / .webp
 * and writes src/modules/eventsGallery/galleryManifest.js
 *
 * Run via: node scripts/generate-gallery-manifest.js
 * Also hooked from package.json prestart / prebuild.
 */
const fs = require('fs');
const path = require('path');

const GALLERY_ROOT = path.join(__dirname, '../public/images/gallery');
const OUT_FILE = path.join(
  __dirname,
  '../src/modules/eventsGallery/galleryManifest.js'
);
const IMAGE_EXT = /\.(jpe?g|webp)$/i;

function naturalCompare(a, b) {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
}

function loadFolderImages(folder) {
  const dir = path.join(GALLERY_ROOT, folder);
  return fs
    .readdirSync(dir)
    .filter((name) => IMAGE_EXT.test(name) && !name.startsWith('.'))
    .sort(naturalCompare)
    .map((file) => {
      const label = file.replace(IMAGE_EXT, '').replace(/[-_]+/g, ' ');
      return {
        src: `/images/gallery/${folder}/${encodeURIComponent(file)}`,
        alt: `${folder} — ${label}`,
        file,
      };
    });
}

function main() {
  if (!fs.existsSync(GALLERY_ROOT)) {
    console.error(`Gallery root missing: ${GALLERY_ROOT}`);
    process.exit(1);
  }

  const folders = fs
    .readdirSync(GALLERY_ROOT, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort(naturalCompare);

  /** @type {Record<string, { src: string, alt: string, file: string }[]>} */
  const manifest = {};
  const summary = [];

  folders.forEach((folder) => {
    const images = loadFolderImages(folder);
    manifest[folder] = images;
    summary.push(`${folder}(${images.length})`);
  });

  const body = `/**
 * Auto-generated by scripts/generate-gallery-manifest.js — do not edit.
 * Drop .jpg / .jpeg / .webp into public/images/gallery/<Folder>/ and re-run
 * (or restart \`pnpm start\` / \`pnpm build\`).
 */
export const GALLERY_MANIFEST = ${JSON.stringify(manifest, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, body, 'utf8');
  console.log(`[gallery] wrote manifest → ${path.relative(process.cwd(), OUT_FILE)}`);
  console.log(`[gallery] ${summary.join(', ') || '(empty)'}`);
}

main();
