/**
 * Scans public/images/seva_smriti/<Folder>/ for .jpg / .jpeg / .webp
 * and writes src/modules/sevaSmriti/smritiManifest.js
 *
 * Run via: node scripts/generate-smriti-manifest.js
 * Also hooked from package.json prestart / prebuild.
 */
const fs = require('fs');
const path = require('path');

const SMRITI_ROOT = path.join(__dirname, '../public/images/seva_smriti');
const OUT_FILE = path.join(
  __dirname,
  '../src/modules/sevaSmriti/smritiManifest.js'
);
const IMAGE_EXT = /\.(jpe?g|webp)$/i;

function naturalCompare(a, b) {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
}

function loadFolderImages(folder) {
  const dir = path.join(SMRITI_ROOT, folder);
  return fs
    .readdirSync(dir)
    .filter((name) => IMAGE_EXT.test(name) && !name.startsWith('.'))
    .sort(naturalCompare)
    .map((file) => {
      const label = file.replace(IMAGE_EXT, '').replace(/[-_]+/g, ' ');
      return {
        src: `/images/seva_smriti/${folder}/${encodeURIComponent(file)}`,
        alt: `${folder} — ${label}`,
        file,
      };
    });
}

function main() {
  if (!fs.existsSync(SMRITI_ROOT)) {
    console.warn(`[smriti] Seva Smriti root not found: ${SMRITI_ROOT} — skipping.`);
    return;
  }

  const folders = fs
    .readdirSync(SMRITI_ROOT, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('.'))
    .map((entry) => entry.name)
    .sort(naturalCompare);

  /** @type {Record<string, { src: string, alt: string, file: string }[]>} */
  const manifest = {};
  const summary = [];

  folders.forEach((folder) => {
    const images = loadFolderImages(folder);
    manifest[folder] = images;
    summary.push(`${folder}(${images.length})`);
  });

  const body = `/**
 * Auto-generated by scripts/generate-smriti-manifest.js — do not edit.
 * Drop .jpg / .jpeg / .webp into public/images/seva_smriti/<Folder>/ and re-run
 * (or restart \`pnpm start\` / \`pnpm build\`).
 */
export const SMRITI_MANIFEST = ${JSON.stringify(manifest, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, body, 'utf8');
  console.log(`[smriti] wrote manifest → ${path.relative(process.cwd(), OUT_FILE)}`);
  console.log(`[smriti] ${summary.join(', ') || '(empty)'}`);
}

main();
